"""Licences of everything OASIS installs to run (PRD L4). NOT run in CI.

    uv run python scripts/licences.py [--out docs/licences.md]

Walks the runtime dependencies of the installed `oasis` package (dev tools excluded) and
prints name, version and licence from each package's own metadata.
"""

from __future__ import annotations

import argparse
import pathlib
import re
from importlib import metadata

_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")


def licence(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    if expr := meta.get("License-Expression"):
        return expr
    classifiers = [
        c.rsplit(" :: ", 1)[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License")
    ]
    if classifiers:
        return ", ".join(classifiers)
    # Some packages paste the whole licence text into License; the first line names it.
    text = (meta.get("License") or "").strip()
    return text.splitlines()[0] if text else "not stated"


def runtime_closure(root: str) -> dict[str, metadata.Distribution]:
    found: dict[str, metadata.Distribution] = {}
    todo = [root]
    while todo:
        name = todo.pop().lower().replace("_", "-")
        if name in found:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue  # an extra or a platform marker that does not apply here
        found[name] = dist
        for req in dist.requires or []:
            # Skip optional extras; environment markers for other platforms fail lookup above.
            if "extra ==" not in req and (m := _NAME.match(req)):
                todo.append(m.group())
    found.pop(root)
    return found


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=pathlib.Path, help="also write the markdown here")
    args = parser.parse_args()
    rows = [
        f"| {d.metadata['Name']} | {d.version} | {licence(d)} |"
        for _, d in sorted(runtime_closure("oasis").items())
    ]
    text = (
        "\n".join(
            [
                "# Licences",
                "",
                "Everything OASIS runs, generated by `scripts/licences.py`.",
                "Development tools are not listed: OASIS does not need them to run.",
                "",
                "| Component | Version | Licence |",
                "|---|---|---|",
                # Not Python packages: checked on the project pages (Hugging Face card, GitHub).
                "| llama.cpp `llama-server` | build 11552 | MIT |",
                "| Qwen3.5-4B GGUF Q4_K_M (unsloth/Qwen3.5-4B-GGUF) | e87f176 | Apache-2.0 |",
                *rows,
            ]
        )
        + "\n"
    )
    print(text)
    if args.out:
        args.out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
