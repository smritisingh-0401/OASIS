"""Build content/help/time_zones.yaml: which country each time zone name belongs to.

The help card opens on the country of the computer's time zone (decision 2026-10-24). The
source is the IANA time zone database as packaged by `tzdata` (public domain), pinned in the
lockfile:
- zone.tab gives one country per zone ("Asia/Kolkata" -> IN);
- browsers may report an older name instead (Chrome: "Asia/Calcutta"). An older name is kept
  only when its rules are byte-identical to zones of exactly one country, so names shared by
  several countries ("CET") are left out and no country is guessed.

Usage:  uv run python scripts/time_zones.py   (rewrites the file; a test checks it is current)
"""

from __future__ import annotations

import importlib.metadata
import importlib.resources
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent.parent / "src/oasis/content/help/time_zones.yaml"


def build() -> dict[str, str]:
    root = importlib.resources.files("tzdata") / "zoneinfo"
    rows = [
        line.split("\t")
        for line in (root / "zone.tab").read_text(encoding="utf-8").splitlines()
        if line and not line.startswith("#")
    ]
    zones = {row[2]: row[0] for row in rows}

    def data(name: str) -> bytes:
        return (root / name).read_bytes()

    countries_by_rules: dict[bytes, set[str]] = {}
    for zone, code in zones.items():
        countries_by_rules.setdefault(data(zone), set()).add(code)

    def names(folder: object, prefix: str = "") -> list[str]:
        out = []
        for item in folder.iterdir():  # type: ignore[attr-defined]
            name = prefix + item.name
            if item.is_dir():
                out += names(item, name + "/")
            elif "/" in name and not name.startswith("Etc/"):
                out.append(name)
        return out

    for name in names(root):
        codes = countries_by_rules.get(data(name), set())
        if name not in zones and len(codes) == 1:
            zones[name] = next(iter(codes))
    return dict(sorted(zones.items()))


def main() -> None:
    body = {
        "schema": "oasis.content/v1",
        "kind": "time_zones",
        "version": importlib.metadata.version("tzdata"),
        "source": "IANA time zone database (zone.tab and zone rules), via the tzdata package",
        "zones": build(),
    }
    header = (
        "# Generated by scripts/time_zones.py from the IANA time zone database (public domain).\n"
        "# Do not edit by hand: rerun the script after a tzdata upgrade.\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + yaml.safe_dump(body, sort_keys=False), encoding="utf-8")
    print(f"{len(body['zones'])} zones -> {OUT}")


if __name__ == "__main__":
    main()
