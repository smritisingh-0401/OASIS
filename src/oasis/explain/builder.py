"""The per-reply explanation record (design §10.2), built after every decision is final.

It explains the response strategy: which detectors fired and why (exact SHAP values), how the
router scored each mode (its exact weighted sum), what the guard did, and the same in plain
words. It never holds the user's text, and its JSON is byte-identical for identical input.
"""

from __future__ import annotations

import functools
import json
import logging
from collections.abc import Mapping, Sequence
from dataclasses import asdict, dataclass, replace
from typing import Any

from oasis.content import load_yaml, require_review
from oasis.core.detectors.lexicon import load
from oasis.core.signals import harsh_label_score
from oasis.explain.shap_values import DetectorExplanation, FeatureValue, explain_lexicon
from oasis.router.weights import config as router_config
from oasis.safety.normalize import base_form
from oasis.types import Mode, Plan, RouteDecision

log = logging.getLogger("oasis.explain")

VERSION = "1"
SCOPE_NOTE = (
    "Explains why this response strategy was chosen. It does not explain the exact wording, "
    "which is generated by a language model."
)
LEXICONS = ("emotions", "cues", "distortions")
TOLERANCE = 1e-6  # additivity: |base + sum(phi) - output| (PRD L1 b)
TOP_SIGNALS = 2  # signals named in the plain-language bullet
HARSH_LABEL = "rule:harsh_label"
PHRASES = ("noticed", "nothing", "trap", "hold", "offer", "step", "fallback", "templated")


@dataclass(frozen=True)
class PlainLanguage:
    phrases: Mapping[str, str]
    signals: Mapping[str, str]
    modes: Mapping[str, str]
    traps: Mapping[str, str]
    reasons: Mapping[str, str]  # planner reason code, or "family.*", -> one bullet


def parse(raw: Mapping[str, Any]) -> PlainLanguage:
    require_review(raw, "plain-language explanations")
    sections = ("phrases", "signals", "modes", "traps", "reasons")
    cfg = PlainLanguage(*(dict(raw[k]) for k in sections))
    router_signals = {s for m in router_config().modes.values() for s in m.weights}
    needed = {
        "phrases": (set(PHRASES), cfg.phrases),
        "signals": (router_signals, cfg.signals),
        "modes": (
            {
                *router_config().modes,
                "grounding",
                "psychoed",
                "assessment",
                "post_crisis",
                "fallback",
            },
            cfg.modes,
        ),
        "traps": (set(load("distortions")), cfg.traps),
        "reasons": (set(), cfg.reasons),
    }
    for what, (keys, given) in needed.items():
        if not keys <= set(given) or not all(isinstance(v, str) and v for v in given.values()):
            raise ValueError(f"plain-language {what} must cover {sorted(keys)}")
    return cfg


@functools.cache
def config() -> PlainLanguage:
    return parse(load_yaml("explain", "plain_language.yaml"))


def build(
    message: str,
    plan: Plan,
    *,
    typed: bool = True,
    attempts: int = 1,
    guard_outcomes: Sequence[str] = ("pass",),
    fallback_reason: str | None = None,
) -> str:
    """The explanation JSON for one reply. `typed` is False for a button press, whose label
    is not the user's words, so no detector is explained."""
    detectors, consistent = _detectors(message) if typed else ([], True)
    consistent = consistent and _router_additive(plan.route)
    if not consistent:
        log.error("explanation inconsistent")  # numbers only reach the record, never the log
    record = {
        "version": VERSION,
        "scope_note": SCOPE_NOTE,
        "status": "ok" if consistent else "inconsistent",
        "plan": {
            "mode": plan.mode,
            "reason_codes": list(plan.reason_codes),
            "templated": plan.templated,
        },
        "router": _router(plan.route),
        "detectors": [asdict(d) for d in detectors],
        "guard": {
            "attempts": attempts,
            "outcomes": list(guard_outcomes),
            "fallback": fallback_reason,
        },
        "plain_language": _plain(plan, fallback_reason),
    }
    return _dumps(record)


def unavailable(reason: str) -> str:
    """The record stored when building failed: the reply went out without an explanation."""
    return _dumps({"version": VERSION, "scope_note": SCOPE_NOTE, "status": "unavailable",
                   "reason": reason})  # fmt: skip


def _dumps(record: Mapping[str, Any]) -> str:
    return json.dumps(record, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _detectors(message: str) -> tuple[list[DetectorExplanation], bool]:
    """Every scorer that fired, and whether each one's values add up (design §10.1)."""
    norm = base_form(message)
    n = len(norm.split())
    out, consistent = [], True
    for file in LEXICONS:
        for name, lex in load(file).items():
            # The scorer's value comes from one segment of the message (Phase 12), so the
            # explanation decomposes that segment.
            part = lex.segment(norm)
            e = explain_lexicon(f"{file}.{name}", lex, part, len(part.split()))
            linear = e.output  # Lexicon.linear: the scorer's own value, before any rule
            if file == "distortions" and name == "labelling":
                rule = harsh_label_score(norm, n)
                e = _with_harsh_label(e, rule)
                # The rule's share must give back the score signals.py uses: the larger one.
                used = max(_clip(linear), rule)
                consistent &= abs(_clip(e.output) - used) < TOLERANCE
            shap_sum = e.base + sum(f.phi for f in e.features if f.feature != HARSH_LABEL)
            consistent &= abs(shap_sum - linear) < TOLERANCE
            if e.output > 0:
                out.append(e)
    return out, consistent


def _with_harsh_label(e: DetectorExplanation, rule: float) -> DetectorExplanation:
    """The harsh-label rule can raise the labelling score above the lexicon's (signals.py
    takes the larger); that share is one more additive feature, so the sum stays exact."""
    bump = rule - _clip(e.output)
    if bump <= 0:
        return e
    features = sorted((*e.features, FeatureValue(HARSH_LABEL, bump)), key=lambda f: -abs(f.phi))
    return replace(e, output=e.output + bump, features=tuple(features))


def _clip(value: float) -> float:
    return min(1.0, max(0.0, value))


def _router_additive(route: RouteDecision | None) -> bool:
    if route is None:
        return True
    return all(
        abs(s.bias + sum(c.value for c in s.contributions) - s.score) < TOLERANCE
        for s in route.scores
    )


def _router(route: RouteDecision | None) -> dict[str, Any] | None:
    if route is None:
        return None
    return {
        "chosen": route.mode,
        "reason": route.reason,
        "offer": route.offer,
        "modes": [
            {
                "mode": s.mode,
                "score": s.score,
                "bias": s.bias,
                "contributions": [asdict(c) for c in s.contributions if c.value],
            }
            for s in route.scores
        ],
    }


def _plain(plan: Plan, fallback_reason: str | None) -> list[str]:
    cfg = config()
    p = cfg.phrases
    bullets = []
    route = plan.route
    if route is not None:
        leader = route.scores[0]
        top = [c.signal for c in leader.contributions if c.value > 0]
        if plan.distortion_types:  # named, with its categories, in the trap bullet below
            top = [s for s in top if s != "distortion"]
        named = [cfg.signals.get(s, s) for s in top[:TOP_SIGNALS]]
        if named:
            bullets.append(p["noticed"].format(signals=" and ".join(named)))
        elif not plan.distortion_types:
            bullets.append(p["nothing"])
    if plan.distortion_types:
        traps = ", ".join(cfg.traps[t] for t in sorted(plan.distortion_types))
        bullets.append(p["trap"].format(traps=traps))
    # Without a route the planner chose the reply by precedence; its reason codes say why.
    reasons = [] if route is not None else [cfg.reasons[k] for k in _reason_keys(plan, cfg)]
    # A listening reply says why it asks nothing, instead of the mode's "asks one question".
    listen = [cfg.reasons[c] for c in plan.reason_codes if c.startswith(("listen.", "brief."))]
    bullets.extend(reasons or listen or [_what_the_reply_does(plan, route, cfg)])
    if fallback_reason is not None:
        bullets.append(p["fallback"])
    return bullets


def _reason_keys(plan: Plan, cfg: PlainLanguage) -> list[str]:
    """The `reasons` entries for this plan's codes, in order, each once."""
    keys: list[str] = []
    for code in plan.reason_codes:
        if code == "assessment.offer" and plan.assessment is not None:
            why = json.loads(plan.assessment.offer_reason).get("reason", "")
            code = f"{code}.{why}"
        family = code.split(".")[0] + ".*"
        key = code if code in cfg.reasons else family if family in cfg.reasons else None
        if key is not None and key not in keys:
            keys.append(key)
    return keys


def _what_the_reply_does(plan: Plan, route: RouteDecision | None, cfg: PlainLanguage) -> str:
    p = cfg.phrases
    if plan.is_step or (route is not None and route.reason == "mid_exercise_hold"):
        return p["step"]
    if route is not None and route.offer is not None:
        return p["offer"].format(mode=_mode_name(route.offer))
    mode: Mode = plan.mode
    sentence = cfg.modes.get(mode, p["templated"])
    if route is not None and (route.reason.startswith("hysteresis")
                              or route.reason == "margin_not_met"):  # fmt: skip
        return f"{p['hold']} {sentence}"
    return sentence


def _mode_name(mode: str) -> str:
    return {"cbt": "CBT", "dbt": "DBT"}.get(mode, mode)
